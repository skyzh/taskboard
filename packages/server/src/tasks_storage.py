"""Storage operations shared by the SQLite ledger and PostgreSQL adapter."""

from contextlib import contextmanager
import re
import sqlite3


_SQL_TOKENS = re.compile(r"""'(?:''|[^'])*'|"(?:""|[^"])*"|\?|(?<!:):([a-zA-Z_]\w*)""")
_JSON = re.compile(r"json_(extract|type)\(((?:\w+\.)?\w+|'\{\}'), '\$\.([a-z_.]+)'\)")
_JSON_INT = {"readiness.source_id", "readiness.after_event", "request_event_id",
             "worker_report_id", "worker_disposition_id"}


def postgres_ddl(statement):
    if not statement.lstrip().upper().startswith(("CREATE TABLE ", "ALTER TABLE ")):
        return statement
    statement = re.sub(r"\bINTEGER\b", "BIGINT", statement)
    statement = re.sub(r"\bBLOB\b", "BYTEA", statement)
    return re.sub(r"(?m)^([ \t]+id) BIGINT PRIMARY KEY,", r"\1 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,", statement)


def postgres_json(match):
    operation, column, path = match.groups()
    parts = path.replace(".", ",")
    json_value = f"(CAST({column} AS jsonb) #> '{{{parts}}}')"
    text_value = f"(CAST({column} AS jsonb) #>> '{{{parts}}}')"
    if operation == "type":
        kind = f"jsonb_typeof({json_value})"
        return f"(CASE {kind} WHEN 'string' THEN 'text' ELSE {kind} END)"
    if path in _JSON_INT:
        return f"CAST({text_value} AS bigint)"
    if path == "feature_deferred":
        return f"(CASE {text_value} WHEN 'true' THEN 1 WHEN '1' THEN 1 ELSE 0 END)"
    return text_value


def postgres_sql(statement, *, bound=False):
    """Translate the SQLite expressions still used by the shared queries."""
    statement = postgres_ddl(statement)
    statement = _JSON.sub(postgres_json, statement)
    statement = re.sub(r"json_array_length\(([\w.]+)\)", r"jsonb_array_length(CAST(\1 AS jsonb))", statement)
    statement = re.sub(r"([\w.]+) COLLATE NOCASE", r"LOWER(\1)", statement)
    if not bound:
        return statement
    escaped = statement.replace("%", "%%")
    return _SQL_TOKENS.sub(
        lambda token: f"%({token[1]})s" if token[1] else "%s" if token[0] == "?" else token[0], escaped,
    )


class Row:
    """Accept the ordinal access and named fields used by SQLite ledger queries."""

    def __init__(self, names, positions, values):
        self.names = names
        self.positions = positions
        self.values = values

    def __getitem__(self, key):
        return self.values[key if isinstance(key, (int, slice)) else self.positions[key]]

    def __iter__(self):
        return iter(self.values)

    def keys(self):
        return list(self.names)

    def __len__(self):
        return len(self.names)


def postgres_row(cursor):
    names = tuple(column.name for column in cursor.description or ())
    positions = dict(reversed(tuple((key, index) for index, key in enumerate(names))))
    return lambda values: Row(names, positions, values)


class Postgres:
    def __init__(self, connection_string):
        try:
            import psycopg
        except ModuleNotFoundError as error:
            raise ValueError("Install PostgreSQL support with uv sync --frozen --extra postgres.") from error
        try:
            # Some shared predicates bind a value only to an IS NULL comparison.
            self.connection = psycopg.connect(
                connection_string, autocommit=True, row_factory=postgres_row, cursor_factory=psycopg.ClientCursor,
            )
        except psycopg.OperationalError:
            raise RuntimeError("Taskboard could not connect to the configured PostgreSQL board.") from None
        self.total_changes = 0

    @property
    def in_transaction(self):
        from psycopg.pq import TransactionStatus

        return self.connection.info.transaction_status != TransactionStatus.IDLE

    def close(self):
        self.connection.close()

    def execute(self, statement, parameters=()):
        statement = postgres_sql(statement, bound=bool(parameters))
        cursor = self.connection.execute(statement, parameters or None)
        if cursor.statusmessage and cursor.statusmessage.split(" ", 1)[0] in ("INSERT", "UPDATE", "DELETE"):
            self.total_changes += cursor.rowcount
        return cursor

    def insert_id(self, statement, parameters):
        return self.execute(statement + " RETURNING id", parameters).fetchone()["id"]

    def columns(self, table):
        return {row["column_name"] for row in self.execute(
            """SELECT column_name FROM information_schema.columns
               WHERE table_schema = current_schema() AND table_name = ?""",
            (table,),
        )}

    def has_table(self, table):
        return bool(self.columns(table))

    @contextmanager
    def migrate(self):
        with self.connection.transaction():
            # Serialize first-time schema creation and subsequent upgrades on this board.
            self.execute("SELECT pg_advisory_xact_lock(hashtext(current_database()), hashtext(current_schema()))")
            self.execute("""
                CREATE TABLE IF NOT EXISTS taskboard_writer (
                    id SMALLINT PRIMARY KEY CHECK (id = 1),
                    schema_version INTEGER NOT NULL
                )
            """)
            self.execute("INSERT INTO taskboard_writer VALUES (1, 0) ON CONFLICT (id) DO NOTHING")
            yield self

    @contextmanager
    def read(self):
        with self.connection.transaction():
            self.execute("SET TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY")
            yield self

    @contextmanager
    def write(self):
        with self.connection.transaction():
            writer = self.execute("SELECT id FROM taskboard_writer WHERE id = 1 FOR UPDATE").fetchone()
            if writer is None:
                raise ValueError("Initialize the PostgreSQL board before writing.")
            yield self


def open_sqlite(path, *, write_existing=True):
    mode = "rw" if write_existing else "ro"
    db = sqlite3.connect(f"{path.as_uri()}?mode={mode}", uri=True)
    db.row_factory = sqlite3.Row
    db.execute("PRAGMA foreign_keys = ON")
    return db


def table_columns(db, table):
    if isinstance(db, Postgres):
        return db.columns(table)
    # The table name is bound rather than interpolated. This also handles old ledgers.
    return {row[0] for row in db.execute("SELECT name FROM pragma_table_info(?)", (table,))}


def has_table(db, table):
    if isinstance(db, Postgres):
        return db.has_table(table)
    return db.execute("SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = ?", (table,)).fetchone() is not None


def insert_id(db, statement, parameters):
    if isinstance(db, Postgres):
        return db.insert_id(statement, parameters)
    return db.execute(statement, parameters).lastrowid


@contextmanager
def read(db):
    if isinstance(db, Postgres):
        with db.read():
            yield db
    else:
        with db:
            db.execute("BEGIN")
            yield db


@contextmanager
def write(db):
    if isinstance(db, Postgres):
        with db.write():
            yield db
    else:
        with db:
            db.execute("BEGIN IMMEDIATE")
            yield db


@contextmanager
def changes(db):
    if isinstance(db, Postgres):
        with db.write():
            yield db
    else:
        with db:
            yield db


def principal_order(db):
    return "principal_order" if isinstance(db, Postgres) else "rowid"


def find_text(db, value, term):
    return f"POSITION({term} IN {value})" if isinstance(db, Postgres) else f"INSTR({value}, {term})"



def greatest(db):
    return "GREATEST" if isinstance(db, Postgres) else "MAX"
